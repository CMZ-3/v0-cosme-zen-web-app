// Build-time script: parse the StockCards Excel into a committed TS data file.
// Run: node scripts/gen-stock-import.mjs
import { read, utils } from "xlsx"
import { readFileSync, writeFileSync } from "node:fs"

const SRC = "data/StockCards_import_clean3-f8099a.xlsx"
const OUT = "lib/db/stock-import-data.ts"

// Excel item_type -> canonical app itemType slug
const TYPE_MAP = {
  RM: "raw_material",
  PK: "packaging",
  PA: "packaging_aux",
  FG: "finished_good",
  OH: "overhead",
  LABOR: "labor",
  TESTER: "tester",
}

const num = (v) => {
  if (v == null || v === "") return 0
  const n = Number(String(v).replace(/,/g, ""))
  return Number.isFinite(n) ? n : 0
}
const str = (v) => {
  if (v == null) return null
  const s = String(v).trim()
  return s === "" ? null : s
}

function inventoryStatus(available, min, max) {
  if (available <= 0) return "out_of_stock"
  if (available < min) return "low"
  if (max > 0 && available > max) return "over_stock"
  return "healthy"
}

const buf = readFileSync(SRC)
const wb = read(buf, { cellDates: true })
const rows = utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { defval: null })

const seen = new Set()
const items = []
let auto = 0

for (const r of rows) {
  const rawCode = str(r.item_code)
  const itemName = str(r.item_name)
  if (!itemName) continue // skip empty rows

  // ensure unique code + id
  let code = rawCode || `AUTO-${String(++auto).padStart(4, "0")}`
  while (seen.has(code)) code = `${code}-${++auto}`
  seen.add(code)

  const excelType = String(r.item_type ?? "RM").trim().toUpperCase()
  const itemType = TYPE_MAP[excelType] ?? "raw_material"

  const balance = num(r.balance ?? r.initial_stock)
  const initial = num(r.initial_stock ?? r.balance)
  const min = num(r.min_stock)
  const max = num(r.max_stock)
  const reorder = num(r.reorder_point) || min
  const available = balance // no reserved/incoming from import

  items.push({
    id: `STK-${code}`,
    itemCode: code,
    itemName,
    itemNameEn: str(r.trade_name) ?? itemName,
    itemType,
    category: str(r.category) ?? excelType,
    unit: str(r.unit) ?? "ชิ้น",
    balance,
    reservedStock: 0,
    incomingStock: 0,
    available,
    initialStock: initial,
    minStock: min,
    maxStock: max,
    reorderPoint: reorder,
    unitCost: num(r.unit_cost),
    supplier: str(r.supplier),
    location: str(r.location),
    barcode: str(r.barcode),
    tradeName: str(r.trade_name),
    inciName: str(r.inci_name),
    casNo: str(r.cas_no),
    storageTemp: null,
    expiryDate: null,
    status: "active",
    inventoryStatus: inventoryStatus(available, min, max),
  })
}

const header = `// AUTO-GENERATED by scripts/gen-stock-import.mjs — do not edit by hand.
// Source: ${SRC} (${items.length} items)
import type { StockCardImport } from "@/lib/stock-types"

export const STOCK_IMPORT_ROWS: StockCardImport[] = ${JSON.stringify(items, null, 2)}
`

writeFileSync(OUT, header)
console.log(`Wrote ${items.length} items to ${OUT}`)
const byType = {}
for (const i of items) byType[i.itemType] = (byType[i.itemType] ?? 0) + 1
console.log("By type:", byType)
